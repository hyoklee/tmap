#!/usr/bin/env python3
"""Write the CLIO CAE OMNI files that download TARGET-MAP and ingest it into the CTE.

The file list is raw/2026-11-05-physionet-target-map-paths.txt: every path in the
project's SHA256SUMS.txt (155 data files plus LICENSE.txt, which is skipped). The
landing page's Table 1 lists only 124 of them and gives a wrong size for the clinical
CSV, so it is no longer used.

Each file is two transfers, run in order by clio_cae:
  1. https://physionet.org/files/target-map/1.0.0/<path> -> file::<data>/<path>
     (HttpFileAssimilator, iowarp/clio-core PR #1331). PhysioNet accepts basic auth
     only from wget, so ~/.clio/cae_http_auth.ini needs client = wget for it
     (see cae_http_auth.ini.example).
  2. the downloaded file -> iowarp::<tag>
     HDF5: format hdf5, one CTE tag per dataset (<tag>/<dataset path>)
     CSV:  format binary, one CTE tag per file
     depends_on names the download's dst, so ingest waits for that download.

With --ingest-only, write target_map_{hdf5,csv}_ingest.omni.yaml instead: step 2 only,
for files already downloaded (for example with cae_http_tool get). Use these for the
full dataset: one clio_cae run that downloads for hours hung the runtime (wiki:
clio-cae-ingest), while ingest alone takes seconds.

With --vol, write target_map_hdf5_vol.omni.yaml: ingest only, HDF5 files only, with
format hdf5_vol and dst "iowarp::". CAE then stages each file in the CLIO HDF5 VOL
connector's own layout (tag "hdf5:<path>", coherence stamp), so a program that opens the
file with HDF5_VOL_CONNECTOR=clio reads it from the CTE. The VOL does not read the
per-dataset tags of format hdf5 (raw/2026-11-07-vol-read-job-7826129.md).

usage: make_omni.py [--data DIR] [--tag-root NAME] [--ingest-only | --vol]
"""
import argparse
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
PATHS = HERE.parent / "raw" / "2026-11-05-physionet-target-map-paths.txt"
BASE_URL = "https://physionet.org/files/target-map/1.0.0"
SMOKE = ["deidentified_target_clinical_data_final.csv", "HDF5_Trimmed/TAR004_D4_ALL_TRIMMED.h5"]

HEADER = """\
# Generated by omni/make_omni.py; edit that script, not this file.
#
# {what}
# Source: PhysioNet TARGET-MAP v1.0.0 (restricted: PhysioNet Restricted Health Data
# License 1.5.0 and DUA). Needs clio-core with PR #1331 (http/https sources, and
# client = wget for physionet.org in ~/.clio/cae_http_auth.ini).
#
#   mkdir -p -m 700 {data}      # before the first run: keep the data private
#   clio_cae {fname}
#
# Each file: an https download to file::, then ingest into the CTE once that download
# is done (depends_on = the download's dst). A re-run skips files already downloaded.
# (*_ingest.omni.yaml and *_vol.omni.yaml files hold the ingest transfers only.)
version: "1.0"

transfers:
"""


def ingest(rel, args):
    """The transfer that ingests one downloaded file into the CTE."""
    local = f"{args.data}/{rel}"
    stem = rel.rsplit("/", 1)[-1].rsplit(".", 1)[0]
    if rel.endswith(".h5") and args.vol:
        return (f'  - src: "hdf5::{local}"\n'
                f'    dst: "iowarp::"\n'
                f'    format: "hdf5_vol"\n')
    if rel.endswith(".h5"):
        return (f'  - src: "hdf5::{local}"\n'
                f'    dst: "iowarp::{args.tag_root}/hdf5/{stem}"\n'
                f'    format: "hdf5"\n')
    return (f'  - src: "file::{local}"\n'
            f'    dst: "iowarp::{args.tag_root}/csv/{stem}"\n'
            f'    format: "binary"\n')


def entries(paths, args):
    for rel in paths:
        if args.ingest_only or args.vol:
            yield f"  # {rel}\n" + ingest(rel, args)
            continue
        local = f"{args.data}/{rel}"
        yield (f"  # {rel}\n"
               f'  - src: "{BASE_URL}/{quote(rel)}"\n'
               f'    dst: "file::{local}"\n'
               f'    format: "binary"\n'
               + ingest(rel, args)
               + f'    depends_on: "file::{local}"\n')


def write(fname, what, paths, args):
    text = HEADER.format(what=f"{what}: {len(paths)} files.", data=args.data, fname=fname)
    text += "\n".join(entries(paths, args))
    (HERE / fname).write_text(text)
    print(f"{fname}: {len(paths)} files")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default="/eagle/radix-io/hyoklee/tmap_data/target-map/1.0.0",
                    help="local copy of the dataset (src/dst paths are not ${VAR}-expanded, so absolute)")
    ap.add_argument("--tag-root", default="target_map", help="CTE tag prefix")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--ingest-only", action="store_true",
                      help="write *_ingest.omni.yaml files for data already downloaded")
    mode.add_argument("--vol", action="store_true",
                      help="write target_map_hdf5_vol.omni.yaml (format hdf5_vol, for the HDF5 VOL)")
    args = ap.parse_args()

    paths = [l.strip() for l in open(PATHS) if l.strip() and not l.startswith("#")]
    data = [p for p in paths if p.endswith((".h5", ".csv"))]
    h5 = [p for p in data if p.endswith(".h5")]
    csvs = [p for p in data if p.endswith(".csv")]
    assert all(s in data for s in SMOKE), "smoke files missing from the path list"

    if args.vol:
        write("target_map_hdf5_vol.omni.yaml",
              "HDF5_Trimmed, staged for the CLIO HDF5 VOL connector (format hdf5_vol). Ingest only:"
              " the files must already be downloaded and verified", h5, args)
        return
    if args.ingest_only:
        note = "Ingest only: the files must already be downloaded and verified"
        write("target_map_hdf5_ingest.omni.yaml", f"HDF5_Trimmed. {note}", h5, args)
        write("target_map_csv_ingest.omni.yaml", f"CSV_files and top-level CSVs. {note}", csvs, args)
        return
    write("target_map_smoke.omni.yaml", "Smoke test: the clinical CSV and one 50.9 MB HDF5 file",
          SMOKE, args)
    write("target_map_hdf5.omni.yaml", "HDF5_Trimmed: raw, unsynchronized recordings", h5, args)
    write("target_map_csv.omni.yaml",
          "CSV_files: synchronized ABP/TCD, plus the clinical CSV and its data dictionary", csvs, args)


if __name__ == "__main__":
    main()
