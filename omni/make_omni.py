#!/usr/bin/env python3
"""Write the CLIO CAE OMNI files that download TARGET-MAP and ingest it into the CTE.

The file list comes from Table 1 of the public PhysioNet landing page
(raw/2026-11-05-physionet-target-map-files.tsv): 124 files, 6.36 GB.

Each file is two transfers, run in order by clio_cae:
  1. https://physionet.org/files/target-map/1.0.0/<dir>/<name> -> file::<data>/<dir>/<name>
     (HttpFileAssimilator, iowarp/clio-core PR #1331; PhysioNet basic auth from
     ~/.clio/cae_http_auth.ini, see cae_http_auth.ini.example)
  2. the downloaded file -> iowarp::<tag>
     HDF5: format hdf5, one CTE tag per dataset (<tag>/<dataset path>)
     CSV:  format binary, one CTE tag per file
     depends_on names the download's dst, so ingest waits for that download.

usage: make_omni.py [--data DIR] [--hdf5-dir NAME] [--csv-dir NAME] [--tag-root NAME]
"""
import argparse
import csv
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
MANIFEST = HERE.parent / "raw" / "2026-11-05-physionet-target-map-files.tsv"
BASE_URL = "https://physionet.org/files/target-map/1.0.0"
CLINICAL = "deidentified_target_clinical_data_final.csv"

HEADER = """\
# Generated by omni/make_omni.py; edit that script, not this file.
#
# {what}
# Source: PhysioNet TARGET-MAP v1.0.0 (restricted: PhysioNet Restricted Health Data
# License 1.5.0 and DUA). Needs clio-core with PR #1331 (http/https sources).
#
#   mkdir -p -m 700 {data}      # before the first run: keep the data private
#   clio_cae {fname}
#
# Each file: an https download to file::, then ingest into the CTE once that download
# is done (depends_on = the download's dst). A re-run skips files already downloaded.
version: "1.0"

transfers:
"""


def entries(rows, args):
    for name, fmt, size in rows:
        sub = "" if name == CLINICAL else (args.hdf5_dir if fmt == "h5" else args.csv_dir)
        rel = f"{sub}/{name}" if sub else name
        local = f"{args.data}/{rel}"
        url = f"{BASE_URL}/{quote(rel)}"
        stem = name.rsplit(".", 1)[0]
        if fmt == "h5":
            ingest = dict(src=f"hdf5::{local}", dst=f"iowarp::{args.tag_root}/hdf5/{stem}", format="hdf5")
        else:
            ingest = dict(src=f"file::{local}", dst=f"iowarp::{args.tag_root}/csv/{stem}", format="binary")
        yield (f"  # {name}  ({int(size):,} bytes)\n"
               f'  - src: "{url}"\n'
               f'    dst: "file::{local}"\n'
               f'    format: "binary"\n'
               f'  - src: "{ingest["src"]}"\n'
               f'    dst: "{ingest["dst"]}"\n'
               f'    format: "{ingest["format"]}"\n'
               f'    depends_on: "file::{local}"\n')


def write(fname, what, rows, args):
    total = sum(int(r[2]) for r in rows)
    text = HEADER.format(what=f"{what}: {len(rows)} files, {total / 1e9:.2f} GB.",
                         data=args.data, fname=fname)
    text += "\n".join(entries(rows, args))
    (HERE / fname).write_text(text)
    print(f"{fname}: {len(rows)} files, {total:,} bytes")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default="/eagle/radix-io/hyoklee/tmap_data/target-map/1.0.0",
                    help="local copy of the dataset (src/dst paths are not ${VAR}-expanded, so absolute)")
    ap.add_argument("--hdf5-dir", default="HDF5_Trimmed", help="server folder of the .h5 files")
    ap.add_argument("--csv-dir", default="CSV_only", help="server folder of the synchronized .csv files")
    ap.add_argument("--tag-root", default="target_map", help="CTE tag prefix")
    args = ap.parse_args()

    with open(MANIFEST) as f:
        rows = [(r["name"], r["format"], r["size_bytes"]) for r in csv.DictReader(f, delimiter="\t")]
    h5 = [r for r in rows if r[1] == "h5"]
    csvs = [r for r in rows if r[1] == "csv"]
    clinical = [r for r in rows if r[0] == CLINICAL]
    smallest_h5 = min(h5, key=lambda r: int(r[2]))

    write("target_map_smoke.omni.yaml", "Smoke test: the clinical CSV and the smallest HDF5 file",
          clinical + [smallest_h5], args)
    write("target_map_hdf5.omni.yaml", "HDF5_Trimmed: raw, unsynchronized recordings", h5, args)
    write("target_map_csv.omni.yaml", "CSV_only: synchronized ABP/TCD, plus the clinical CSV", csvs, args)


if __name__ == "__main__":
    main()
